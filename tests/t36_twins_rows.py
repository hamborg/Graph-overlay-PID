import asyncio, sys, json, os
sys.path.insert(0, sys.argv[2])
from common import *
OUT = sys.argv[1]; FX = sys.argv[3]
PANEL = '() => document.querySelector(".tv2-panel").innerText.replace(/\\n+/g, " | ").slice(0, 500)'
async def main():
    async with async_playwright() as p:
        b, pg, logs = await open_page(p, init=open(sys.argv[2] + '/mock_claude.js').read())
        await wait_ready(pg)
        # 1. same-as twins in the card
        await pg.fill('#search', 'AHU_HTRK-VEN03_SupplyFan'); await pg.keyboard.press('Enter'); await pg.wait_for_timeout(600)
        print('card name', await pg.inner_text('#insp h3'))
        print('via badges', await pg.evaluate('[...document.querySelectorAll("#insp .via")].map(x => x.closest(".rel, .prop, dd") ? (x.closest(".rel, .prop, dd").innerText.replace(/\\n/g, " ")) : x.innerText).slice(0, 10)'))
        # twins come after own rows in each group
        print('order ok', await pg.evaluate('''[...document.querySelectorAll("#insp .insp-sec")].every(sec => { let seenTwin = false, ok = true; for (const el of sec.children) { if (el.matches("h4") || el.matches("div.muted")) seenTwin = false; if (el.matches(".twin")) seenTwin = true; else if (el.matches(".rel, .prop") && seenTwin) ok = false; } return ok; })'''))
        await pg.screenshot(path=f'{OUT}/360_card_twins.png')
        # 2. evidence with the twin's section
        await pg.click('#btnEvidence'); await pg.wait_for_timeout(600)
        print('evidence heads', await pg.evaluate('[...document.querySelectorAll("#evidence .ev-twinhead")].map(x => x.innerText)'))
        print('evidence badge', await pg.inner_text('#evidence header .badge'))
        await pg.screenshot(path=f'{OUT}/361_evidence_twins.png')
        # 3. SPARQL in plain words replaces the editor text, also with a ```sql tag and an echoed query
        await pg.click('#btnSparql'); await pg.wait_for_timeout(300)
        await pg.fill('#sqEditor', 'SELECT ?old WHERE { ?old a brick:Fan }')
        await pg.evaluate('window.__mock.sparqlText = "Here it is:\\n```sql\\nSELECT ?x WHERE { ?x a brick:Damper }\\n```\\nNote: dampers."')
        await pg.fill('.sq-nl-q', 'all dampers'); await pg.click('.sq-nl button.primary'); await pg.wait_for_timeout(800)
        print('editor A', json.dumps(await pg.input_value('#sqEditor')))
        await pg.evaluate('window.__mock.sparqlText = "```sparql\\nSELECT ?x WHERE { ?x a brick:Damper }\\n```\\nChanged to:\\n```sparql\\nSELECT ?x ?l WHERE { ?x a brick:Damper ; rdfs:label ?l }\\n```\\nNote: with labels."')
        await pg.click('.sq-nl label.check input'); await pg.fill('.sq-nl-q', 'add labels'); await pg.click('.sq-nl button.primary'); await pg.wait_for_timeout(800)
        print('editor B', json.dumps(await pg.input_value('#sqEditor')))
        await pg.evaluate('window.__mock.sparqlText = "PREFIX brick: <https://brickschema.org/schema/Brick#>\\nSELECT ?f WHERE { ?f a brick:Fan }\\nNote: fans."')
        await pg.click('.sq-nl label.check input'); await pg.fill('.sq-nl-q', 'fans'); await pg.click('.sq-nl button.primary'); await pg.wait_for_timeout(800)
        print('editor C', json.dumps(await pg.input_value('#sqEditor')))
        # 4. resizing: side panel, right panel, card
        print('sel before drags', await pg.evaluate('window.__kgov.selection.length'))
        g0 = await pg.evaluate('getComputedStyle(document.querySelector(".main")).gridTemplateColumns')
        bx = await pg.locator('#szSide').bounding_box()
        await pg.mouse.move(bx['x'] + 4, 400); await pg.mouse.down(); await pg.mouse.move(bx['x'] + 104, 400, steps=5); await pg.mouse.up(); await pg.wait_for_timeout(200)
        bx = await pg.locator('#szRight').bounding_box()
        await pg.mouse.move(bx['x'] + 4, 400); await pg.mouse.down(); await pg.mouse.move(bx['x'] - 116, 400, steps=5); await pg.mouse.up(); await pg.wait_for_timeout(200)
        g1 = await pg.evaluate('getComputedStyle(document.querySelector(".main")).gridTemplateColumns')
        print('grid', g0, '->', g1, '| sizes', await pg.evaluate('localStorage.getItem("kgov:sizes")'))
        print('sel after drags', await pg.evaluate('window.__kgov.selection.length'))
        await pg.click('#sparql header .x-btn'); await pg.wait_for_timeout(200)
        print('insp state', await pg.evaluate('({hidden: document.querySelector("#insp").hidden, grips: document.querySelectorAll("#insp > .sz-grip").length, sel: window.__kgov.selection.length})'))
        if await pg.evaluate('document.querySelector("#insp").hidden'):
            await pg.fill('#search', 'AHU_HTRK-VEN03_SupplyFan'); await pg.keyboard.press('Enter'); await pg.wait_for_timeout(600)
        w0 = await pg.evaluate('document.querySelector("#insp").getBoundingClientRect().width')
        gb = await pg.locator('#insp > .sz-grip.bl').bounding_box()
        await pg.mouse.move(gb['x'] + 8, gb['y'] + 8); await pg.mouse.down(); await pg.mouse.move(gb['x'] + 8 - 140, gb['y'] + 8 + 60, steps=5); await pg.mouse.up(); await pg.wait_for_timeout(200)
        print('card', round(w0), '->', round(await pg.evaluate('document.querySelector("#insp").getBoundingClientRect().width')))
        await pg.screenshot(path=f'{OUT}/362_resized.png')
        # 5. point list: add a point, change it, delete, undo
        await pg.locator('.sb-tab.table').first.click(); await pg.wait_for_timeout(400)
        t0 = await pg.evaluate('({n: window.__kgov.tables[0].rows.length, text: window.__kgov.tables[0].text.split(/\\n/).slice(0,3)})')
        print('table', t0)
        await pg.get_by_role('button', name='+ Add point').click(); await pg.wait_for_timeout(200)
        print('form', await pg.evaluate(PANEL))
        ins = pg.locator('.tv2-form .tv2-fields input')
        print('fields', await ins.count())
        await ins.nth(0).fill('AHU01-XT99')
        if await ins.count() > 1: await ins.nth(1).fill('New test sensor, with comma')
        if await pg.locator('.tv2-form details').count():
            await pg.click('.tv2-form details summary'); await pg.fill('.tv2-form details input[type=search]', 'VI-TT0'); await pg.wait_for_timeout(150)
            await pg.locator('.tv2-form details .tv2-hit').first.click(); await pg.wait_for_timeout(100)
        await pg.get_by_role('button', name='Add row').click(); await pg.wait_for_timeout(400)
        t1 = await pg.evaluate('(() => { const t = window.__kgov.tables[0]; return { n: t.rows.length, last: t.rows[t.rows.length - 1], lastLine: t.text.trim().split(/\\r?\\n/).pop(), links: t.links[t.rows.length - 1], edited: t.text !== t.origText }; })()')
        print('after add', t1)
        print('panel', await pg.evaluate(PANEL))
        await pg.screenshot(path=f'{OUT}/363_added.png')
        # insert below row 1 → edits of later rows move down
        await pg.locator('.tv2-row[data-row="0"] td.rn').click(); await pg.wait_for_timeout(150)
        await pg.get_by_role('button', name='Add a point below').click(); await pg.wait_for_timeout(150)
        await pg.locator('.tv2-form .tv2-fields input').nth(0).fill('AHU01-INSERTED')
        await pg.get_by_role('button', name='Add row').click(); await pg.wait_for_timeout(300)
        print('inserted', await pg.evaluate('(() => { const t = window.__kgov.tables[0]; return { r1: t.rows[1], n: t.rows.length, linkKeys: Object.keys(t.links) }; })()'))
        await pg.get_by_role('button', name='Change this row…').click(); await pg.wait_for_timeout(150)
        await pg.locator('.tv2-form .tv2-fields input').nth(0).fill('AHU01-CHANGED')
        await pg.get_by_role('button', name='Save row').click(); await pg.wait_for_timeout(300)
        print('changed', await pg.evaluate('window.__kgov.tables[0].rows[1]'))
        await pg.get_by_role('button', name='Delete row').click(); await pg.wait_for_timeout(300)
        print('deleted', await pg.evaluate('(() => { const t = window.__kgov.tables[0]; return { r1: t.rows[1][0], n: t.rows.length, linkKeys: Object.keys(t.links) }; })()'))
        await pg.get_by_role('button', name='↶ Undo').click(); await pg.wait_for_timeout(300)
        print('undo delete', await pg.evaluate('(() => { const t = window.__kgov.tables[0]; return { r1: t.rows[1][0], n: t.rows.length }; })()'))
        await pg.get_by_role('button', name='Save list file').click(); await pg.wait_for_timeout(300)
        print('saved', await pg.evaluate('window.__mock.saved.slice(-1).map(s => [s.filename, s.data.split(/\\n/).length])'))
        # undo all three, back to the original text
        for _ in range(3): await pg.get_by_role('button', name='↶ Undo').click(); await pg.wait_for_timeout(200)
        print('all undone', await pg.evaluate('(() => { const t = window.__kgov.tables[0]; return { n: t.rows.length, same: t.text === t.origText }; })()'))
        await pg.screenshot(path=f'{OUT}/364_list.png')
        print('LOGS', [l for l in logs if ('error' in l.lower() and 'ERR_' not in l) or 'PAGEERROR' in l][:6])
        await b.close()
asyncio.run(main())
